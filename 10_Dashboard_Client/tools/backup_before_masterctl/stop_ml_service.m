function stop_ml_service()
%STOP_ML_SERVICE  Stop the FastAPI diagnosis service that listens on 127.0.0.1:8000 (started by ensure_ml_service).
%   Stops the process that holds the port and the cmd.exe that started it (WMI launch, 15 Oct 2026). Safe to call when nothing runs.
cmd = ['powershell -NoProfile -NonInteractive -Command "' ...
    '$c = Get-NetTCPConnection -LocalAddress 127.0.0.1 -LocalPort 8000 -State Listen -ErrorAction SilentlyContinue; ' ...
    'foreach ($x in $c) { $p = Get-CimInstance Win32_Process -Filter (\"ProcessId=\" + $x.OwningProcess); ' ...
    'if ($p -and $p.ParentProcessId) { Stop-Process -Id $p.ParentProcessId -Force -ErrorAction SilentlyContinue }; ' ...
    'Stop-Process -Id $x.OwningProcess -Force -ErrorAction SilentlyContinue }"'];
system(cmd);
end
