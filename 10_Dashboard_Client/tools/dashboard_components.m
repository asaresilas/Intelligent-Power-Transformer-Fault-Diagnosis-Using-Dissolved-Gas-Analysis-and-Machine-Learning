    ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Text = ''Record number (row)'''})];
r = r + 1;  C = [C, add('RecordSpinner', 'ControlGrid', 'uispinner(app.ControlGrid)', { ...
    'Limits = [1 1]', 'RoundFractionalValues = ''on''', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Value = 1'})];
r = r + 1;  C = [C, add('DiagnoseButton', 'ControlGrid', 'uibutton(app.ControlGrid, ''push'')', { ...
    'ButtonPushedFcn = createCallbackFcn(app, @DiagnoseButtonPushed, true)', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', ...
