% tab 1: charts
C = [C, add('ChartsTab', 'MainTabs', 'uitab(app.MainTabs)', {'Title = ''Charts'''})];
C = [C, add('ChartsGrid', 'ChartsTab', 'uigridlayout(app.ChartsTab)', {'ColumnWidth = {''1x'', ''1x'', ''1x''}', 'RowHeight = {''1x''}', 'Padding = [2 2 2 2]'})];
