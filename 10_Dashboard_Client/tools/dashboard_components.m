    'FontWeight = ''bold''', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Text = ''2  Oil samples to examine'''})];
r = r + 1;  C = [C, add('SampleSetDropDown', 'ControlGrid', 'uidropdown(app.ControlGrid)', { ...
    'Items = {''Mixed: healthy + every fault type (7)'', ''Random held-out records (7)'', ''First 4 held-out records (test run)''}', ...
    'ItemsData = {''mixed'', ''random'', ''first''}', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Value = ''mixed'''})];
r = r + 1;  C = [C, add('RunSimulationButton', 'ControlGrid', 'uibutton(app.ControlGrid, ''push'')', { ...
    'ButtonPushedFcn = createCallbackFcn(app, @RunSimulationButtonPushed, true)', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', ...
    'FontWeight = ''bold''', 'Text = ''Run simulation + diagnose'''})];
