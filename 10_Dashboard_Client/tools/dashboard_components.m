C = [C, add('ExplainTab', 'MainTabs', 'uitab(app.MainTabs)', {'Title = ''Explanation in words'''})];
C = [C, add('ExplainGrid', 'ExplainTab', 'uigridlayout(app.ExplainTab)', {'ColumnWidth = {''1x''}', 'RowHeight = {''1x''}', 'Padding = [2 2 2 2]'})];
C = [C, add('ExplainArea', 'ExplainGrid', 'uitextarea(app.ExplainGrid)', {'Editable = ''off''', 'FontSize = 12', 'Layout.Row = 1', 'Layout.Column = 1'})];
