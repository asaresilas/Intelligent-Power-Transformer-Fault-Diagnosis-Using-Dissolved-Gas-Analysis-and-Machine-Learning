    'ColumnWidth = {''1x'', ''1x'', ''1x'', ''1x'', ''1x''}', 'RowHeight = {''1x''}', 'ColumnSpacing = 6', 'Padding = [0 0 0 0]', 'Layout.Row = 2', 'Layout.Column = 1'})];
cards = {'Rogers', 'Rogers ratio (IEEE C57.104)'; 'IEC', 'IEC 60599 ratio method'; 'Duval', 'Duval Triangle 1'; ...
         'ML', 'Machine learning (Random Forest)'; 'Ref', 'Known label of the record'};
