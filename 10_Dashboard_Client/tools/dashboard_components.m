    C = [C, add([n 'Card'], 'CardsGrid', 'uipanel(app.CardsGrid)', {['Title = ''' cards{k, 2} ''''], 'FontWeight = ''bold''', ...
        'Layout.Row = 1', ['Layout.Column = ' num2str(k)]})]; %#ok<AGROW>
    C = [C, add([n 'Grid'], [n 'Card'], ['uigridlayout(app.' n 'Card)'], {'ColumnWidth = {''1x''}', 'RowHeight = {34, ''1x'', 24}', ...
        'RowSpacing = 2', 'Padding = [4 2 4 2]'})]; %#ok<AGROW>
    C = [C, add([n 'Answer'], [n 'Grid'], ['uilabel(app.' n 'Grid)'], {'FontSize = 22', 'FontWeight = ''bold''', ...
        'HorizontalAlignment = ''center''', 'Layout.Row = 1', 'Layout.Column = 1', 'Text = ''-'''})]; %#ok<AGROW>
    C = [C, add([n 'Note'], [n 'Grid'], ['uilabel(app.' n 'Grid)'], {'FontSize = 11', 'WordWrap = ''on''', 'VerticalAlignment = ''top''', ...
        'HorizontalAlignment = ''center''', 'Layout.Row = 2', 'Layout.Column = 1', 'Text = '''''})]; %#ok<AGROW>
    C = [C, add([n 'Judge'], [n 'Grid'], ['uilabel(app.' n 'Grid)'], {'FontSize = 12', 'FontWeight = ''bold''', 'WordWrap = ''on''', ...
        'HorizontalAlignment = ''center''', 'Layout.Row = 3', 'Layout.Column = 1', 'Text = '''''})]; %#ok<AGROW>
end

