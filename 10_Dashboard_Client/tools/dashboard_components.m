    'ColumnName = {''#''; ''Time h''; ''Record''; ''Known label''; ''Rogers''; ''IEC 60599''; ''Duval''; ''ML''; ''Agree of 3''; ''Verdict''; ''Hot-spot degC''}', ...
    'ColumnWidth = {32, 58, 112, 86, 66, 82, 66, 66, 78, 130, ''auto''}', 'RowName = {}', 'FontSize = 11', 'Layout.Row = 3', 'Layout.Column = 1', ...
    'CellSelectionCallback = createCallbackFcn(app, @EventTableCellSelection, true)'})];

