    'title(app.ad_CODENAME_ad, ''ML probability of each fault type'')', 'Layout.Row = 1', 'Layout.Column = 3'})];
% tab 2: step by step
C = [C, add('StepsTab', 'MainTabs', 'uitab(app.MainTabs)', {'Title = ''Step by step'''})];
C = [C, add('StepsGrid', 'StepsTab', 'uigridlayout(app.StepsTab)', {'ColumnWidth = {''1x''}', 'RowHeight = {''1x''}', 'Padding = [2 2 2 2]'})];
