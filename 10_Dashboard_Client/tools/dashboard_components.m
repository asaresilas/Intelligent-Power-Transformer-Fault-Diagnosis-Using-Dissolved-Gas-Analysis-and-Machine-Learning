    'ColumnName = {''Gas''; ''ppm''}', 'RowName = {}', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1'})];
r = r + 1;  C = [C, add('RestartServiceButton', 'ControlGrid', 'uibutton(app.ControlGrid, ''push'')', { ...
    'ButtonPushedFcn = createCallbackFcn(app, @RestartServiceButtonPushed, true)', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', ...
    'Text = ''Restart ML service'''})];
r = r + 1;  C = [C, add('StatusLabel', 'ControlGrid', 'uilabel(app.ControlGrid)', { ...
    'WordWrap = ''on''', 'VerticalAlignment = ''top''', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Text = '''''})];

%% right: verdict, cards, samples, tabs -----------------------------------------------------------------------------------
C = [C, add('RightGrid', 'GridLayout', 'uigridlayout(app.GridLayout)', { ...
    'ColumnWidth = {''1x''}', 'RowHeight = {108, 128, 176, ''1x''}', 'RowSpacing = 6', 'Padding = [0 0 0 0]', 'Layout.Row = 1', 'Layout.Column = 2'})];
C = [C, add('VerdictPanel', 'RightGrid', 'uipanel(app.RightGrid)', { ...
    'BorderType = ''none''', 'BackgroundColor = [0.45 0.45 0.45]', 'Layout.Row = 1', 'Layout.Column = 1'})];
C = [C, add('VerdictGrid', 'VerdictPanel', 'uigridlayout(app.VerdictPanel)', { ...
    'ColumnWidth = {''1x'', 190}', 'RowHeight = {34, ''1x'', ''1x''}', 'RowSpacing = 2', 'BackgroundColor = [0.45 0.45 0.45]', 'Padding = [10 4 10 4]'})];
C = [C, add('VerdictLabel', 'VerdictGrid', 'uilabel(app.VerdictGrid)', { ...
    'FontSize = 21', 'FontWeight = ''bold''', 'FontColor = [1 1 1]', 'Layout.Row = 1', 'Layout.Column = 1', 'Text = ''WAITING FOR A SAMPLE'''})];
