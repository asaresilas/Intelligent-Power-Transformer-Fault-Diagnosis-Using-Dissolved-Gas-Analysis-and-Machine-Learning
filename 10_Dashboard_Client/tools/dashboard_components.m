    'ButtonPushedFcn = createCallbackFcn(app, @LoadDGAFileButtonPushed, true)', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', ...
    'Text = ''Load measured DGA file'''})];
r = r + 1;  C = [C, add('FaultFilterDropDown', 'ControlGrid', 'uidropdown(app.ControlGrid)', { ...
    'Items = {''Any record'', ''Healthy (Normal)'', ''PD partial discharge'', ''D1 low-energy discharge'', ''D2 high-energy discharge'', ''T1 thermal below 300 C'', ''T2 thermal 300-700 C'', ''T3 thermal above 700 C''}', ...
    'ItemsData = {''All'', ''Normal'', ''PD'', ''D1'', ''D2'', ''T1'', ''T2'', ''T3''}', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', 'Value = ''All'''})];
r = r + 1;  C = [C, add('RandomRecordButton', 'ControlGrid', 'uibutton(app.ControlGrid, ''push'')', { ...
    'ButtonPushedFcn = createCallbackFcn(app, @RandomRecordButtonPushed, true)', ['Layout.Row = ' num2str(r)], 'Layout.Column = 1', ...
    'Text = ''Pick random record'''})];
